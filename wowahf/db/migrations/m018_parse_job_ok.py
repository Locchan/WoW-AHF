VERSION = "018_parse_job_ok"


def upgrade(conn) -> None:
    """
    Track successful completion of parses and jobs so a crash mid-run can
    be detected on startup and incomplete work purged / retried.

    Existing parses are marked ok except the newest row (last run was an
    OOM mid-parse and must stay unsuccessful for startup recovery).
    """
    with conn.cursor() as cur:
        cur.execute(
            """
            ALTER TABLE public.parses
            ADD COLUMN IF NOT EXISTS ok BOOLEAN NOT NULL DEFAULT FALSE
            """
        )
        cur.execute(
            """
            UPDATE public.parses
            SET ok = TRUE
            WHERE id < (SELECT coalesce(max(id), 0) FROM parses)
            """
        )

        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS job_runs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                job_name TEXT NOT NULL,
                started_at TIMESTAMPTZ NOT NULL,
                finished_at TIMESTAMPTZ,
                ok BOOLEAN NOT NULL DEFAULT FALSE
            )
            """
        )
        cur.execute(
            """
            CREATE INDEX IF NOT EXISTS idx_job_runs_name_id
            ON public.job_runs (job_name, id DESC)
            """
        )
