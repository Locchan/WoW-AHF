VERSION = "010_pg_baseline"


def upgrade(conn) -> None:
    """
    Postgres baseline: public tables, maintenance helpers, pg_cron schedules.
    House tables are created on demand via ensure_house_tables.
    """
    with conn.cursor() as cur:
        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS parses (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                parsed_at TIMESTAMPTZ NOT NULL
            )
            """
        )
        cur.execute(
            "CREATE INDEX IF NOT EXISTS idx_parses_parsed_at ON parses (parsed_at)"
        )
        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS auction_houses (
                id INT PRIMARY KEY,
                name VARCHAR(128) NOT NULL
            )
            """
        )
        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS items (
                id INT PRIMARY KEY,
                name VARCHAR(255) NULL,
                is_commodity BOOLEAN NOT NULL DEFAULT FALSE,
                name_status TEXT NOT NULL DEFAULT 'pending',
                updated_at TIMESTAMPTZ NOT NULL
            )
            """
        )
        cur.execute(
            "CREATE INDEX IF NOT EXISTS idx_items_commodity ON items (is_commodity)"
        )
        cur.execute(
            "CREATE INDEX IF NOT EXISTS idx_items_name_status ON items (name_status)"
        )
        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS market_stats (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                parse_id BIGINT NOT NULL,
                ah_id INT NOT NULL,
                metric VARCHAR(64) NOT NULL,
                value NUMERIC(20, 2) NOT NULL,
                UNIQUE (parse_id, ah_id, metric)
            )
            """
        )
        cur.execute(
            """
            CREATE INDEX IF NOT EXISTS idx_ms_parse_ah_metric
            ON market_stats (parse_id, ah_id, metric)
            """
        )
        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS market_price (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                parse_id BIGINT NOT NULL,
                ah_id INT NOT NULL,
                item_id INT NOT NULL,
                price BIGINT NOT NULL,
                UNIQUE (parse_id, ah_id, item_id)
            )
            """
        )
        cur.execute(
            """
            CREATE INDEX IF NOT EXISTS idx_mp_parse_ah
            ON market_price (parse_id, ah_id)
            """
        )
        cur.execute(
            """
            CREATE INDEX IF NOT EXISTS idx_mp_item_parse
            ON market_price (item_id, parse_id)
            """
        )
        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS market_depth (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                parse_id BIGINT NOT NULL,
                ah_id INT NOT NULL,
                item_id INT NOT NULL,
                depth BIGINT NOT NULL,
                UNIQUE (parse_id, ah_id, item_id)
            )
            """
        )
        cur.execute(
            """
            CREATE INDEX IF NOT EXISTS idx_md_parse_ah
            ON market_depth (parse_id, ah_id)
            """
        )
        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS market_spread (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                parse_id BIGINT NOT NULL,
                ah_id INT NOT NULL,
                item_id INT NOT NULL,
                spread NUMERIC(20, 2) NOT NULL,
                UNIQUE (parse_id, ah_id, item_id)
            )
            """
        )
        cur.execute(
            """
            CREATE INDEX IF NOT EXISTS idx_mspread_parse_ah
            ON market_spread (parse_id, ah_id)
            """
        )
        cur.execute(
            """
            CREATE TABLE IF NOT EXISTS schema_event_runs (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                event_name VARCHAR(64) NOT NULL,
                started_at TIMESTAMPTZ NOT NULL,
                finished_at TIMESTAMPTZ NULL,
                ok BOOLEAN NULL,
                error_message VARCHAR(512) NULL
            )
            """
        )
        cur.execute(
            """
            CREATE INDEX IF NOT EXISTS idx_ser_event_started
            ON schema_event_runs (event_name, started_at)
            """
        )

        cur.execute(
            """
            CREATE OR REPLACE FUNCTION maintenance_purge_old_ah_raw()
            RETURNS void
            LANGUAGE plpgsql
            AS $$
            DECLARE
                r RECORD;
                run_id BIGINT;
                err TEXT;
            BEGIN
                INSERT INTO schema_event_runs (event_name, started_at)
                VALUES ('purge_ah_raw_daily', clock_timestamp())
                RETURNING id INTO run_id;
                BEGIN
                    FOR r IN
                        SELECT tablename
                        FROM pg_tables
                        WHERE schemaname = 'data_raw'
                          AND tablename ~ '^ah_raw_[0-9]+$'
                    LOOP
                        EXECUTE format(
                            'DELETE FROM data_raw.%I r
                             USING parses p
                             WHERE p.id = r.parse_id
                               AND p.parsed_at < clock_timestamp() - interval ''24 hours''',
                            r.tablename
                        );
                    END LOOP;
                    UPDATE schema_event_runs
                    SET finished_at = clock_timestamp(), ok = TRUE
                    WHERE id = run_id;
                EXCEPTION WHEN OTHERS THEN
                    GET STACKED DIAGNOSTICS err = MESSAGE_TEXT;
                    UPDATE schema_event_runs
                    SET finished_at = clock_timestamp(),
                        ok = FALSE,
                        error_message = left(err, 512)
                    WHERE id = run_id;
                    RAISE;
                END;
            END;
            $$
            """
        )
        cur.execute(
            """
            CREATE OR REPLACE FUNCTION maintenance_cull_inactive_ah_watch()
            RETURNS void
            LANGUAGE plpgsql
            AS $$
            DECLARE
                r RECORD;
                run_id BIGINT;
                err TEXT;
                deleted INT;
            BEGIN
                INSERT INTO schema_event_runs (event_name, started_at)
                VALUES ('cull_ah_watch_8h', clock_timestamp())
                RETURNING id INTO run_id;
                BEGIN
                    FOR r IN
                        SELECT tablename
                        FROM pg_tables
                        WHERE schemaname = 'data_watch'
                          AND tablename ~ '^ah_watch_[0-9]+$'
                    LOOP
                        LOOP
                            EXECUTE format(
                                'WITH doomed AS (
                                    SELECT auc_id FROM data_watch.%I
                                    WHERE active IS FALSE
                                    LIMIT 5000
                                 )
                                 DELETE FROM data_watch.%I w
                                 USING doomed d
                                 WHERE w.auc_id = d.auc_id
                                 RETURNING 1',
                                r.tablename, r.tablename
                            );
                            GET DIAGNOSTICS deleted = ROW_COUNT;
                            EXIT WHEN deleted = 0;
                        END LOOP;
                    END LOOP;
                    UPDATE schema_event_runs
                    SET finished_at = clock_timestamp(), ok = TRUE
                    WHERE id = run_id;
                EXCEPTION WHEN OTHERS THEN
                    GET STACKED DIAGNOSTICS err = MESSAGE_TEXT;
                    UPDATE schema_event_runs
                    SET finished_at = clock_timestamp(),
                        ok = FALSE,
                        error_message = left(err, 512)
                    WHERE id = run_id;
                    RAISE;
                END;
            END;
            $$
            """
        )

        # pg_cron schedules are installed by LocInfra setup-auth (superuser).
